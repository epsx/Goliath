std::string trim_input_value(const std::string& value) {
    const std::size_t start = value.find_first_not_of(" \t\r\n");
    if (start == std::string::npos) return {};
    const std::size_t end = value.find_last_not_of(" \t\r\n");
    return value.substr(start, end - start + 1);
}

std::optional<int> decimal_in_range(std::string_view text,
                                    int minimum,
                                    int maximum) {
    if (text.empty()) return std::nullopt;

    int value = 0;
    for (const char ch : text) {
        if (!std::isdigit(static_cast<unsigned char>(ch)))
            return std::nullopt;
        value = value * 10 + (ch - '0');
        if (value > maximum) return std::nullopt;
    }
    return value >= minimum ? std::optional<int>(value) : std::nullopt;
}

bool is_known_input_definition(const std::string& section,
                               const std::string& key) {
    const auto sectionIt = input_defs().find(section);
    if (sectionIt == input_defs().end()) return false;
    return std::find(sectionIt->second.begin(), sectionIt->second.end(), key) !=
           sectionIt->second.end();
}

bool is_safe_jgrf_binding(const std::string& value,
                          bool analogDefinition) {
    if (value.empty()) return false;

    if (value[0] == 'j') {
        // JGRF 2.0.1 reads the frontend port directly from value[1], so only
        // the single-digit form generated by its own input configurator is
        // safe here.
        if (value.size() < 4 || value[1] < '0' || value[1] > '9')
            return false;

        if (value[2] == 'a') {
            if (value[3] < '0' ||
                value[3] >= '0' + kJgrfJoystickAxisCount) {
                return false;
            }
            if (analogDefinition) return value.size() == 4;
            return value.size() == 5 &&
                   (value[4] == '+' || value[4] == '-');
        }

        if (analogDefinition) return false;
        if (value[2] == 'b') {
            return decimal_in_range(
                       std::string_view(value).substr(3), 0,
                       kJgrfJoystickButtonCount - 1)
                .has_value();
        }
        if (value[2] == 'h') {
            return value.size() == 5 && value[3] == '0' &&
                   value[4] >= '0' &&
                   value[4] < '0' + kJgrfHatDirectionCount;
        }
        return false;
    }

    if (analogDefinition) return false;
    if (value.starts_with("mb")) {
        return decimal_in_range(
                   std::string_view(value).substr(2), 0,
                   kJgrfJoystickButtonCount - 1)
            .has_value();
    }

    return decimal_in_range(value, 0, SDL_SCANCODE_COUNT - 1).has_value();
}

