std::pair<std::string, std::string> normalize_input_value(const std::string& valueIn) {
    std::string value = trim_input_value(valueIn);

    if (value.starts_with("j") || value.starts_with("mb")) {
        return {value, value};
    }

    try {
        std::size_t pos = 0;
        int num = std::stoi(value, &pos);
        if (pos == value.size()) {
            auto& names = sdl_scancode_names();
            auto it = names.find(num);
            std::string name = it != names.end() ? it->second : std::to_string(num);
            return {std::to_string(num), name + " (" + std::to_string(num) + ")"};
        }
    } catch (...) {
        // fall through
    }

    std::string alias;
    for (char c : value) {
        if (c == ' ') continue;
        alias += (char)std::tolower((unsigned char)c);
    }
    auto& n2s = name_to_sdl_scancode();
    auto it = n2s.find(alias);
    if (it != n2s.end()) {
        int num = it->second;
        auto& names = sdl_scancode_names();
        auto nit = names.find(num);
        std::string name = nit != names.end() ? nit->second : alias;
        return {std::to_string(num), name + " (" + std::to_string(num) + ")"};
    }

    return {value, value};
}

std::string canonical_input_key(const std::string& section, const std::string& key) {
    auto& defs = input_defs();
    auto secIt = defs.find(section);
    if (secIt != defs.end()) {
        for (const auto& canon : secIt->second) {
            if (canon == key) return canon;
        }
        std::string lower = key;
        std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
        for (const auto& canon : secIt->second) {
            std::string canonLower = canon;
            std::transform(canonLower.begin(), canonLower.end(), canonLower.begin(), ::tolower);
            if (canonLower == lower) return canon;
        }
    }
    return key;
}

int geolith_input_setting_for_device(int device) {
    switch (device) {
        case 1: return 1; // Neo Geo Joysticks
        case 2: return 2; // Mahjong
        case 3: return 3; // 4-Player
        case 4: return 0; // V-Liner: auto-detected from the loaded game
        case 5: return 0; // Irritating Maze: auto-detected from the loaded game
        default: return 1;
    }
}

bool is_analog_input_definition(const std::string& section, const std::string& key) {
    return section == "neogeoirrmaze" && (key == "XAxis" || key == "YAxis");
}

bool is_joystick_axis_binding(const std::string& valueIn) {
    return is_safe_jgrf_binding(trim_input_value(valueIn), true);
}

std::optional<std::string> normalize_input_binding_for_definition(
        const std::string& section,
        const std::string& key,
        const std::string& value) {
    const std::string canonicalKey = canonical_input_key(section, key);
    if (!is_known_input_definition(section, canonicalKey))
        return std::nullopt;

    const std::string stored = normalize_input_value(value).first;
    if (!is_safe_jgrf_binding(
            stored, is_analog_input_definition(section, canonicalKey))) {
        return std::nullopt;
    }
    return stored;
}

std::optional<std::string> jgrf_hotkey_action(int scancode) {
    // Keep this table synchronized with JGRF src/input.c's direct,
    // modifier-free frontend hotkeys. Shift+1..8 are intentionally omitted:
    // those only trigger input configuration while Shift is held.
    static const std::map<int, std::string> hotkeys = {
        {41, "Quit"},
        {43, "Open Menu"},
        {53, "Fast-forward"},
        {58, "Soft Reset"},
        {59, "Hard Reset"},
        {62, "Save State (Slot 0)"},
        {63, "Save State (Slot 1)"},
        {64, "Load State (Slot 0)"},
        {65, "Load State (Slot 1)"},
        {66, "Screenshot"},
        {69, "Toggle Cheats On/Off"},
        {9,  "Toggle Fullscreen/Windowed Mode"},
        {16, "Toggle Audio Playback (Mute/Unmute)"},
        {19, "Pause / Resume"},
    };

    auto it = hotkeys.find(scancode);
    if (it == hotkeys.end()) return std::nullopt;
    return it->second;
}

std::optional<std::string> jgrf_hotkey_action_for_binding(const std::string& value) {
    const auto normalized = normalize_input_value(value);
    const std::string& stored = normalized.first;
    if (stored.empty() || stored.starts_with("j") || stored.starts_with("mb")) {
        return std::nullopt;
    }

    try {
        std::size_t pos = 0;
        const int scancode = std::stoi(stored, &pos);
        if (pos != stored.size()) return std::nullopt;
        return jgrf_hotkey_action(scancode);
    } catch (...) {
        return std::nullopt;
    }
}

